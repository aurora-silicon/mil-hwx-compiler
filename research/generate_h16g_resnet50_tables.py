#!/usr/bin/env python3
"""Generate the public-clean exact ResNet-50 H16G task-fact table.

Input is the sanitized JSON produced by decode_h16g_resnet50_full.py.  The
output contains decoded task headers, record headers, and register values;
it never reads or embeds an HWX payload or kernel bytes.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def record_addresses(header: int, count: int) -> list[int]:
    base = (header & 0x7FFF) * 4
    if header & 0x80000000:
        result = [base]
        result.extend(base + 4 * (bit + 1)
                      for bit in range(16) if header & (1 << (15 + bit)))
    else:
        result = [base + 4 * index for index in range(count)]
    if len(result) != count:
        raise ValueError(
            f"record 0x{header:08x} decodes {len(result)} values, expected {count}")
    return result


def generate(facts: dict) -> str:
    tasks = []
    records = []
    values = []
    for group in facts["groups"]:
        for header_words, record_list, blocks in zip(
                group["header_words"], group["records"],
                group["register_blocks"]):
            registers = {int(address, 16): int(value, 16)
                         for block in blocks.values()
                         for address, value in block["words"].items()}
            record_start = len(records)
            for record in record_list:
                header = int(record["header"], 16)
                addresses = record_addresses(header, record["count"])
                value_start = len(values)
                try:
                    values.extend(registers[address] for address in addresses)
                except KeyError as error:
                    raise ValueError(
                        f"record address 0x{error.args[0]:x} has no decoded value") from error
                records.append((header, value_start, len(addresses)))
            tasks.append(([int(word, 16) for word in header_words],
                          record_start, len(records) - record_start))
    if len(tasks) != 82:
        raise ValueError(f"expected 82 ResNet tasks, got {len(tasks)}")

    lines = [
        "// Generated by research/generate_h16g_resnet50_tables.py from",
        "// sanitized decoded facts. No HWX or kernel payload bytes are present.",
        "static constexpr ResNetRecordFact resnetRecordFacts[] = {",
    ]
    lines.extend(f"    {{0x{header:08x}u, {start}u, {count}u}},"
                 for header, start, count in records)
    lines.append("};")
    lines.append("static constexpr U32 resnetRecordValues[] = {")
    for at in range(0, len(values), 8):
        lines.append("    " + ", ".join(
            f"0x{value:08x}u" for value in values[at:at + 8]) + ",")
    lines.append("};")
    lines.append("static constexpr ResNetTaskFact resnetTaskFacts[] = {")
    for header, start, count in tasks:
        words = ", ".join(f"0x{word:08x}u" for word in header)
        lines.append(f"    {{{{{words}}}, {start}u, {count}u}},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("facts", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    facts = json.loads(args.facts.read_text())
    args.output.write_text(generate(facts))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

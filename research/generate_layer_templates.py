#!/usr/bin/env python3
"""Generate native layer fields from decoded JSON, verifying source constants.

No Apple container or constant blob is an input. Every accepted point is
checked against its hash before its decoded task fields enter the table.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct

from h13_td import decode_task
from layer_constants import resize_constants, hard_swish_constants
from mint_conv_probes import h13_task_words, h14_task_words, word_rows

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "plugins/NativeLayerTemplates.inc"


def records():
    for target in ("h13", "h14"):
        for path in sorted((ROOT / "research/oracles" / target).glob("layer_*.json")):
            record = json.loads(path.read_text())
            if record.get("error") or record["family"] not in (
                    "layer_resize", "layer_activation", "layer_concat"):
                continue
            p = record["parameters"]
            if record["family"] == "layer_resize":
                # Prefer the resize spelling; the upsample twins prove aliasing.
                if not p["operation"].startswith("resize_"):
                    continue
                operation = "Nearest2x" if p["operation"] == "resize_nearest_neighbor" else "BilinearHalf2x"
                inp = p["input_shape"]
                assert p["output_shape"] == [1, inp[1], 2 * inp[2], 2 * inp[3]]
                if operation == "BilinearHalf2x":
                    assert p["mode"] == "UNALIGN_CORNERS"
                constants = resize_constants(operation, inp[1], target == "h14")
                other = 0
            elif record["family"] == "layer_concat":
                operation = "Concat"
                inp, rhs = p["input_shapes"]
                assert inp[0] == rhs[0] == 1 and inp[2:] == rhs[2:]
                other = rhs[1]
                constants = bytes(record["constant_section"]["size"])
            elif p["operation"] == "sigmoid":
                operation, other = "Sigmoid", 0
                inp = p["input_shape"]
                # Reconstruct the existing LUT from its small decoded numerical
                # oracle; LayerOps.cpp reuses the established unary encoder.
                small = json.loads((ROOT / "research/oracles" / target /
                    "layer_sigmoid_c1_16x16.json").read_text())
                constants = bytearray(record["constant_section"]["size"])
                for word in small["constant_section"]["nonzero_fp16_words"]:
                    struct.pack_into("<e", constants, word["index"] * 2, word["value"])
            elif record["case"].startswith("layer_hardswish_arithmetic_"):
                operation, other = "HardSwish", 0
                inp = p["input_shape"]
                constants = hard_swish_constants(record["constant_section"]["size"], inp[1], target == "h14")
            else:
                # Rejected/direct/default-hard-sigmoid forms are evidence only.
                continue
            assert hashlib.sha256(constants).hexdigest() == record["constant_section"]["sha256"], path
            yield target, operation, (inp[1], inp[2], inp[3], other), record


def generate():
    lines = ["// Generated by research/generate_layer_templates.py from decoded facts.",
             "// No Apple container bytes or constant payloads."]
    rows = []
    for index, (target, operation, shape, record) in enumerate(records()):
        words = [] if target == "h13" else [0] * 4
        for ti, task in enumerate(record["task_descriptors"]):
            rebuilt = (h13_task_words if target == "h13" else h14_task_words)(task)
            assert decode_task(struct.pack(f"<{len(rebuilt)}I", *rebuilt), target) == task
            words.extend(rebuilt)
            if ti + 1 < len(record["task_descriptors"]):
                next_bytes = int(task["header_words"][7], 16) if target == "h13" else (len(words) * 4 + 15) // 16 * 16
                words.extend([0] * (next_bytes // 4 - len(words)))
        symbol = f"nativeLayer{index}"
        lines += [f"static constexpr std::uint32_t {symbol}[] = {{", *word_rows(words), "};"]
        pd = record["program_descriptor"]
        offset = int(pd["constant_address"], 16) - int(pd["text_address"], 16)
        assert offset == (len(words) * 4 + 63) // 64 * 64
        trailer = pd.get("trailing_words")
        record_count = int(trailer[20], 16) if trailer else 0
        unresolved = int(trailer[28], 16) if trailer else 0
        rows.append(f"    {{{str(target == 'h14').lower()}, Operation::{operation}, "
                    f"{{{', '.join(map(str, shape))}}}, {symbol}, std::size({symbol}), "
                    f"{record['task_descriptors'][0]['size_bytes']}, {len(record['task_descriptors'])}, "
                    f"{offset}, {record['constant_section']['size']}, {record_count}, {unresolved}}},")
    lines += ["static constexpr NativeLayer kNativeLayers[] = {", *rows, "};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text = generate()
    if args.check:
        assert OUTPUT.read_text() == text, "native layer templates are stale"
    else:
        OUTPUT.write_text(text)
    print("native layer templates: up to date")

#!/usr/bin/env python3
"""Generate the public-clean H13 ResNet-50 task-field table.

Input is sanitized decoder JSON: task headers, register-record headers, and
decoded register values only.  The generator never reads an HWX payload or
kernel section; constant bytes are always rebuilt from the licensed model.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path


def generate(decoded: dict) -> str:
    tasks: list[tuple[list[int], int, int]] = []
    records: list[tuple[int, int, int]] = []
    values: list[int] = []
    for task in decoded["task_descriptors"]:
        registers = {
            int(address, 16): int(value, 16)
            for block in task["blocks"].values()
            for address, value in block["words"].items()
        }
        record_start = len(records)
        for record in task["records"]:
            base = int(record["address"], 16)
            count = int(record["count"])
            value_start = len(values)
            values.extend(registers[base + 4 * index] for index in range(count))
            records.append((int(record["header"], 16), value_start, count))
        tasks.append(([int(word, 16) for word in task["header_words"]],
                      record_start, len(records) - record_start))
    if len(tasks) != 80:
        raise ValueError(f"expected 80 ResNet tasks, got {len(tasks)}")

    lines = [
        "// Generated by research/generate_h13_resnet50_tables.py from",
        "// sanitized decoded fields. No HWX or kernel payload bytes are present.",
        "static constexpr H13ResNetRecordFact h13ResNetRecordFacts[] = {",
    ]
    lines.extend(f"    {{0x{header:08x}u, {start}u, {count}u}},"
                 for header, start, count in records)
    lines.append("};")
    lines.append("static constexpr std::uint32_t h13ResNetRecordValues[] = {")
    for at in range(0, len(values), 8):
        lines.append("    " + ", ".join(
            f"0x{value:08x}u" for value in values[at:at + 8]) + ",")
    lines.append("};")
    lines.append("static constexpr H13ResNetTaskFact h13ResNetTaskFacts[] = {")
    for header, start, count in tasks:
        words = ", ".join(f"0x{word:08x}u" for word in header)
        lines.append(f"    {{{{{words}}}, {start}u, {count}u}},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("decoded", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    decoded = json.loads(args.decoded.read_text())
    args.output.write_text(generate(decoded))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
